"""``sunstone migrate``: rewrite datasets.yaml, its include files and datasets.lock.yaml to the new key form."""

from __future__ import annotations

import re
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

from ruamel.yaml.error import YAMLError

from .aliases import (
    NormalizeResult,
    ensure_min_version,
    lock_uses_new_form,
    make_yaml,
    normalize_document,
    normalize_lock,
)
from .conformance import split_camel, validate_datasets_yaml

LOCK_HEADER = "# Auto-generated by sunstone. Do not edit manually.\n"
_ARRAY_RE = re.compile(r"\[\d+\]")


@dataclass(frozen=True)
class UnknownKey:
    path: str
    key: str
    suggestions: list[str]
    file: str = ""


@dataclass(frozen=True)
class MigrationConflict:
    """``old`` was kept in ``file`` because ``new`` already holds a different value."""

    file: str
    path: str
    old: str
    new: str


@dataclass(frozen=True)
class SkippedInclude:
    file: str
    reason: str


@dataclass(frozen=True)
class AmbiguousEntry:
    file: str
    path: str


class MigrateError(Exception):
    """The main datasets file cannot be read; nothing was written."""


@dataclass
class MigrationReport:
    changed: dict[str, int] = field(default_factory=dict)
    unknown: list[UnknownKey] = field(default_factory=list)
    dry_run: bool = False
    conflicts: list[MigrationConflict] = field(default_factory=list)
    skipped: list[SkippedInclude] = field(default_factory=list)
    ambiguous: list[AmbiguousEntry] = field(default_factory=list)

    @property
    def failed(self) -> bool:
        return bool(self.conflicts or self.skipped or self.ambiguous)


def _write(path: Path, data: Any, *, header: str = "") -> None:
    yaml = make_yaml()
    ca = getattr(data, "ca", None)
    if header and ca is not None:
        ca.comment = None
    with open(path, "w") as f:
        if header:
            f.write(header)
        yaml.dump(data, f)


def _suggest(key: str, path: str) -> list[str]:
    from .vocab import level_for_path
    from .vocab_search import search

    level_path = _ARRAY_RE.sub("", path)
    at = level_path if level_for_path(level_path) is not None else None
    return [t.curie for t in search(split_camel(key), at=at, limit=3)]


def _left_alone(path: str, result: NormalizeResult) -> bool:
    """True for a path under an ambiguous entry or an old key kept by a conflict."""
    prefixes = list(result.ambiguous)
    prefixes += [f"{c.path}.{c.old}" if c.path else c.old for c in result.conflicts]
    return any(path == p or path.startswith((p + ".", p + "[")) for p in prefixes)


def _unknown_keys(doc: Any, file: str, result: NormalizeResult) -> list[UnknownKey]:
    found = []
    for v in validate_datasets_yaml(doc, normalize=False, result=NormalizeResult()):
        if v.rule_id != "R301" or _left_alone(v.path, result):
            continue
        container, _, key = v.path.rpartition(".")
        found.append(UnknownKey(v.path, key, _suggest(key, container), file))
    return found


def _include_problem(inc: Any) -> str | None:
    from .datasets import DatasetsManager

    if not isinstance(inc, dict):
        return "not a mapping"
    if "include" in inc:
        return "nested includes are not supported"
    bad = DatasetsManager._INCLUDE_DISALLOWED_KEYS & set(inc)
    if bad:
        return f"disallowed top-level keys: {', '.join(sorted(bad))}"
    return None


def _load(yaml: Any, path: Path) -> Any:
    with open(path, "r") as f:
        return yaml.load(f) or {}


def migrate_project(
    project_path: Path | str, *, datasets_file: str = "datasets.yaml", dry_run: bool = False
) -> MigrationReport:
    """Migrate the project. Every file is loaded and normalized before any is written.

    ``min_sunstone_version`` in the main file is raised when any file (main, include or lock)
    is or becomes new-form, so older readers refuse the project instead of dropping keys.
    """
    project = Path(project_path).resolve()
    main_path = project / datasets_file
    yaml = make_yaml()
    report = MigrationReport(dry_run=dry_run)
    writes: list[tuple[Path, Any, str]] = []

    def record(name: str, result: NormalizeResult) -> None:
        report.conflicts.extend(MigrationConflict(name, c.path, c.old, c.new) for c in result.conflicts)
        report.ambiguous.extend(AmbiguousEntry(name, p) for p in result.ambiguous)

    try:
        main = _load(yaml, main_path)
    except YAMLError as e:
        raise MigrateError(f"invalid YAML in {main_path.name}: {e}") from e
    main_result = normalize_document(main)
    needs_min = bool(main_result.renames or main_result.new_form)
    record(main_path.name, main_result)
    report.unknown.extend(_unknown_keys(main, "", main_result))

    for rel in main.get("include") or []:
        name = Path(str(rel)).as_posix()
        inc_path = (main_path.parent / str(rel)).resolve()
        if not inc_path.is_file():
            report.skipped.append(SkippedInclude(name, "file not found"))
            continue
        try:
            inc = _load(yaml, inc_path)
        except YAMLError as e:
            report.skipped.append(SkippedInclude(name, f"invalid YAML: {e}"))
            continue
        problem = _include_problem(inc)
        if problem:
            report.skipped.append(SkippedInclude(name, problem))
            continue
        inc_result = normalize_document(inc)
        needs_min = needs_min or bool(inc_result.renames or inc_result.new_form)
        record(name, inc_result)
        if inc_result.renames:
            report.changed[name] = len(inc_result.renames)
            writes.append((inc_path, inc, ""))
        report.unknown.extend(_unknown_keys(inc, name, inc_result))

    lock_path = main_path.parent / "datasets.lock.yaml"
    if lock_path.exists():
        try:
            lock = _load(yaml, lock_path)
        except YAMLError as e:
            report.skipped.append(SkippedInclude(lock_path.name, f"invalid YAML: {e}"))
        else:
            lock_new = lock_uses_new_form(lock)
            lock_result = normalize_lock(lock)
            needs_min = needs_min or lock_new or bool(lock_result.renames)
            record(lock_path.name, lock_result)
            if lock_result.renames:
                report.changed[lock_path.name] = len(lock_result.renames)
                writes.append((lock_path, lock, LOCK_HEADER))

    main_changes = len(main_result.renames) + int(needs_min and ensure_min_version(main))
    if main_changes:
        report.changed = {main_path.name: main_changes, **report.changed}
        writes.insert(0, (main_path, main, ""))

    if not dry_run:
        for path, data, header in writes:
            _write(path, data, header=header)
    return report
