def _project(tmp_path: Path) -> Path:
    (tmp_path / "datasets.yaml").write_text(MAIN)
    (tmp_path / "extra.yaml").write_text(EXTRA)
    (tmp_path / "datasets.lock.yaml").write_text(LOCK)
    return tmp_path


def test_migrate_rewrites_all_files_and_keeps_comments(tmp_path: Path) -> None:
    proj = _project(tmp_path)
    report = migrate_project(proj)
    assert (proj / "datasets.yaml").read_text() == EXPECTED_MAIN
    extra = (proj / "extra.yaml").read_text()
    assert "title: Out" in extra and "si:unit: kg" in extra and "schema:" in extra
    lock = (proj / "datasets.lock.yaml").read_text()
    assert lock.startswith("# Auto-generated by sunstone. Do not edit manually.\n")
    assert "prov:wasAttributedTo: E" in lock and "dct:license: MIT" in lock
    assert set(report.changed) == {"datasets.yaml", "extra.yaml", "datasets.lock.yaml"}
    assert report.changed["datasets.lock.yaml"] == 2
    assert "min_sunstone_version" not in extra, "include files never carry min_sunstone_version"


def test_migrate_sets_min_version_on_already_new_form_file(tmp_path: Path) -> None:
    (tmp_path / "datasets.yaml").write_text(
        "inputs: []\noutputs:\n  - title: Out\n    name: out\n    path: outputs/out.csv\n"
    )
    report = migrate_project(tmp_path)
    assert report.changed == {"datasets.yaml": 1}
    assert (tmp_path / "datasets.yaml").read_text().startswith("min_sunstone_version: 1.20.0\n")
    (tmp_path / "datasets.yaml").write_text("min_sunstone_version: 2.0.0\ninputs: []\noutputs: []\n")
    assert migrate_project(tmp_path).changed == {}


def test_migrate_is_idempotent(tmp_path: Path) -> None:
    proj = _project(tmp_path)
    migrate_project(proj)
    before = {p.name: p.read_bytes() for p in proj.glob("*.yaml")}
    report = migrate_project(proj)
    assert report.changed == {}
    assert {p.name: p.read_bytes() for p in proj.glob("*.yaml")} == before


def test_migrate_reports_unknown_keys_with_suggestions(tmp_path: Path) -> None:
    proj = _project(tmp_path)
    report = migrate_project(proj)
    unknown = {u.key: u for u in report.unknown}
    assert unknown["coverage"].path == "inputs[0].coverage"
    assert unknown["coverage"].suggestions[0] == "dct:coverage"


def test_dry_run_changes_nothing(tmp_path: Path) -> None:
    proj = _project(tmp_path)
    before = (proj / "datasets.yaml").read_text()
    report = migrate_project(proj, dry_run=True)
    assert report.dry_run and report.changed["datasets.yaml"] > 0
    assert (proj / "datasets.yaml").read_text() == before


def test_cli_output(tmp_path: Path) -> None:
    proj = _project(tmp_path)
    r = CliRunner().invoke(app, ["migrate", "-f", str(proj / "datasets.yaml")])
    assert r.exit_code == 0, r.output
    assert "datasets.yaml: " in r.output and "key(s) renamed" in r.output
    assert "inputs[0].coverage" in r.output and "dct:coverage" in r.output
    r2 = CliRunner().invoke(app, ["migrate", "-f", str(proj / "datasets.yaml")])
    assert "Nothing to migrate" in r2.output


