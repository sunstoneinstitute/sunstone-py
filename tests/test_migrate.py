CONFLICT = """\
inputs:
  - name: Raw
    slug: raw
    location: inputs/raw.csv
    path: inputs/other.csv
"""


def test_conflict_keeps_old_key_reports_and_exits_nonzero(tmp_path: Path) -> None:
    (tmp_path / "datasets.yaml").write_text(CONFLICT)
    report = migrate_project(tmp_path)
    assert [(c.file, c.path, c.old, c.new) for c in report.conflicts] == [
        ("datasets.yaml", "inputs[0]", "location", "path")
    ]
    text = (tmp_path / "datasets.yaml").read_text()
    assert "location: inputs/raw.csv" in text and "path: inputs/other.csv" in text
    r = CliRunner().invoke(app, ["migrate", "-f", str(tmp_path / "datasets.yaml")])
    assert r.exit_code == 1
    assert "datasets.yaml" in r.output and "'location' kept" in r.output and "'path'" in r.output


def test_conflict_in_json_output(tmp_path: Path) -> None:
    import json

    (tmp_path / "datasets.yaml").write_text(CONFLICT)
    r = CliRunner().invoke(app, ["migrate", "--json", "-f", str(tmp_path / "datasets.yaml")])
    assert r.exit_code == 1
    data = json.loads(r.output)
    assert data["conflicts"] == [{"file": "datasets.yaml", "path": "inputs[0]", "old": "location", "new": "path"}]


def test_clean_run_exits_zero_with_empty_conflicts(tmp_path: Path) -> None:
    import json

    proj = _project(tmp_path)
    r = CliRunner().invoke(app, ["migrate", "--json", "-f", str(proj / "datasets.yaml")])
    assert r.exit_code == 0, r.output
    assert json.loads(r.output)["conflicts"] == []


def test_unmergeable_includes_are_skipped_others_migrated(tmp_path: Path) -> None:
    proj = _project(tmp_path)
    (proj / "datasets.yaml").write_text(
        MAIN.replace("  - extra.yaml\n", "  - extra.yaml\n  - missing.yaml\n  - nested.yaml\n")
    )
    (proj / "nested.yaml").write_text("include:\n  - extra.yaml\n")
    report = migrate_project(proj)
    assert {s.file: s.reason for s in report.skipped}.keys() == {"missing.yaml", "nested.yaml"}
    assert "extra.yaml" in report.changed and "datasets.yaml" in report.changed
    r = CliRunner().invoke(app, ["migrate", "-f", str(proj / "datasets.yaml")])
    assert r.exit_code == 1 and "missing.yaml" in r.output


AMBIG = """\
inputs:
  - name: Raw
    slug: raw
    title: Raw
    location: inputs/raw.csv
"""


def test_ambiguous_entries_reported_in_main_and_include(tmp_path: Path) -> None:
    import json

    (tmp_path / "datasets.yaml").write_text("include:\n  - extra.yaml\n" + AMBIG)
    (tmp_path / "extra.yaml").write_text(AMBIG.replace("inputs", "outputs"))
    report = migrate_project(tmp_path)
    assert {(a.file, a.path) for a in report.ambiguous} == {
        ("datasets.yaml", "inputs[0]"),
        ("extra.yaml", "outputs[0]"),
    }
    assert not [u for u in report.unknown if u.key == "location"]
    r = CliRunner().invoke(app, ["migrate", "-f", str(tmp_path / "datasets.yaml")])
    assert r.exit_code == 1 and "both slug and title present; resolve by hand" in r.output
    r = CliRunner().invoke(app, ["migrate", "--json", "-f", str(tmp_path / "datasets.yaml")])
    assert r.exit_code == 1 and len(json.loads(r.output)["ambiguous"]) == 2


