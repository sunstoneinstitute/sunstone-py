def test_malformed_include_is_skipped_others_migrated(tmp_path: Path) -> None:
    proj = _project(tmp_path)
    (proj / "datasets.yaml").write_text(MAIN.replace("  - extra.yaml\n", "  - extra.yaml\n  - bad.yaml\n"))
    (proj / "bad.yaml").write_text("inputs: [unclosed\n")
    report = migrate_project(proj)
    assert [s.file for s in report.skipped] == ["bad.yaml"] and report.skipped[0].reason.startswith("invalid YAML: ")
    assert (proj / "bad.yaml").read_text() == "inputs: [unclosed\n"
    assert "min_sunstone_version" in (proj / "datasets.yaml").read_text()
    assert "title: Out" in (proj / "extra.yaml").read_text()
    r = CliRunner().invoke(app, ["migrate", "-f", str(proj / "datasets.yaml")])
    assert r.exit_code == 1


def test_malformed_main_writes_nothing_and_exits_2(tmp_path: Path) -> None:
    (tmp_path / "datasets.yaml").write_text("inputs: [unclosed\n")
    (tmp_path / "datasets.lock.yaml").write_text(LOCK)
    r = CliRunner().invoke(app, ["migrate", "-f", str(tmp_path / "datasets.yaml")])
    assert r.exit_code == 2
    assert (tmp_path / "datasets.yaml").read_text() == "inputs: [unclosed\n"
    assert (tmp_path / "datasets.lock.yaml").read_text() == LOCK


def test_include_only_change_pins_main(tmp_path: Path) -> None:
    (tmp_path / "datasets.yaml").write_text("include:\n  - extra.yaml\ninputs: []\noutputs: []\n")
    (tmp_path / "extra.yaml").write_text(EXTRA)
    report = migrate_project(tmp_path)
    assert report.changed["datasets.yaml"] == 1
    assert (tmp_path / "datasets.yaml").read_text().startswith("min_sunstone_version: 1.20.0\n")
    assert "min_sunstone_version" not in (tmp_path / "extra.yaml").read_text()


def test_lock_only_change_pins_main(tmp_path: Path) -> None:
    (tmp_path / "datasets.yaml").write_text("inputs: []\noutputs: []\n")
    (tmp_path / "datasets.lock.yaml").write_text(LOCK)
    report = migrate_project(tmp_path)
    assert report.changed == {"datasets.yaml": 1, "datasets.lock.yaml": 2}
    assert (tmp_path / "datasets.yaml").read_text().startswith("min_sunstone_version: 1.20.0\n")


def test_already_new_form_lock_pins_main(tmp_path: Path) -> None:
    (tmp_path / "datasets.yaml").write_text("inputs: []\noutputs: []\n")
    new_lock = LOCK.replace("attributedTo", "prov:wasAttributedTo").replace("license", "dct:license")
    (tmp_path / "datasets.lock.yaml").write_text(new_lock)
    assert migrate_project(tmp_path).changed == {"datasets.yaml": 1}
    assert migrate_project(tmp_path).changed == {}
    assert (tmp_path / "datasets.lock.yaml").read_text() == new_lock
